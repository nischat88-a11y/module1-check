import psutil
print("CPU %:", psutil.cpu_percent())
print("Cores:", psutil.cpu_count(logical=False))
print("Threads:", psutil.cpu_count(logical=True))
print("CPU Speed:", psutil.cpu_freq())
print("RAM %:", psutil.virtual_memory().percent)
print("RAM Full:", psutil.virtual_memory())
print("Disk C: %:", psutil.disk_usage('C:').percent)
print("Disk D: %:", psutil.disk_usage('D:').percent)
print("Disk C: Full:", psutil.disk_usage('C:'))
print("All Drives:", psutil.disk_partitions())
print("Battery:", psutil.sensors_battery())
print("Boot Time:", psutil.boot_time())
print("Users:", psutil.users())